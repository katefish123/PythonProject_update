// Optional named-port integration example. All ports are in clk domain.
// A supplies complete-source-frame storage, ordered responses and reset flushing.
// A/C supply video adaptation, clocks/CDC and the actual board-level interfaces.
// Override SRC/OUT and marker parameters from the agreed system configuration.
// This is not a board top; do not bind its algorithm buses to package pins.
module b_rectifier_instance #(
 parameter SRC_W=640,SRC_H=480,OUT_W=320,OUT_H=452,UPDATE_EVERY=5,
 parameter MIN_PIXELS=16,MAX_PIXELS=4096,MAX_SPAN=128,
 parameter BLACK_RMIN=0,BLACK_RMAX=64,BLACK_GMIN=0,BLACK_GMAX=64,BLACK_BMIN=0,BLACK_BMAX=64,
 // Inclusive, non-overlapping windows in source coordinates; P0/P1/P2/P3 = TL/TR/BR/BL.
 // Integer division places the center column/row of an odd source in right/bottom ROIs.
 parameter P0_XMIN=0,P0_XMAX=SRC_W/2-1,P0_YMIN=0,P0_YMAX=SRC_H/2-1,
 parameter P1_XMIN=SRC_W/2,P1_XMAX=SRC_W-1,P1_YMIN=0,P1_YMAX=SRC_H/2-1,
 parameter P2_XMIN=SRC_W/2,P2_XMAX=SRC_W-1,P2_YMIN=SRC_H/2,P2_YMAX=SRC_H-1,
 parameter P3_XMIN=0,P3_XMAX=SRC_W/2-1,P3_YMIN=SRC_H/2,P3_YMAX=SRC_H-1
)(
 input wire clk,rst_n,
 input wire src_valid,src_frame_start,src_frame_end,
 input wire [11:0] src_x,src_y, input wire [23:0] src_rgb,
 input wire dst_valid,dst_frame_start,nearest,
 input wire [11:0] dst_x,dst_y,
 output wire corners_valid,marker_reject,marker_dropped,solver_reject,
 output wire [11:0] x0,y0,x1,y1,x2,y2,x3,y3,
 output wire geometry_valid,params_pending, output wire [15:0] stale_frames,
 output wire req_valid,req_inside,req_error,
 output wire [23:0] req_tag,addr00,addr10,addr01,addr11,
 output wire [7:0] req_fx,req_fy,
 input wire rsp_valid,rsp_inside,
 input wire [23:0] rsp_tag,p00,p10,p01,p11,
 input wire [7:0] rsp_fx,rsp_fy,
 output wire out_valid, output wire [23:0] out_rgb,out_tag
);

 b_rectifier #(
  .SRC_W(SRC_W),
  .SRC_H(SRC_H),
  .OUT_W(OUT_W),
  .OUT_H(OUT_H),
  .UPDATE_EVERY(UPDATE_EVERY),
  .MIN_PIXELS(MIN_PIXELS),
  .MAX_PIXELS(MAX_PIXELS),
  .MAX_SPAN(MAX_SPAN),
  .BLACK_RMIN(BLACK_RMIN),
  .BLACK_RMAX(BLACK_RMAX),
  .BLACK_GMIN(BLACK_GMIN),
  .BLACK_GMAX(BLACK_GMAX),
  .BLACK_BMIN(BLACK_BMIN),
  .BLACK_BMAX(BLACK_BMAX),
  .P0_XMIN(P0_XMIN),
  .P0_XMAX(P0_XMAX),
  .P0_YMIN(P0_YMIN),
  .P0_YMAX(P0_YMAX),
  .P1_XMIN(P1_XMIN),
  .P1_XMAX(P1_XMAX),
  .P1_YMIN(P1_YMIN),
  .P1_YMAX(P1_YMAX),
  .P2_XMIN(P2_XMIN),
  .P2_XMAX(P2_XMAX),
  .P2_YMIN(P2_YMIN),
  .P2_YMAX(P2_YMAX),
  .P3_XMIN(P3_XMIN),
  .P3_XMAX(P3_XMAX),
  .P3_YMIN(P3_YMIN),
  .P3_YMAX(P3_YMAX)
 ) u_rectifier (
  .clk(clk),
  .rst_n(rst_n),
  .src_valid(src_valid),
  .src_frame_start(src_frame_start),
  .src_frame_end(src_frame_end),
  .src_x(src_x),
  .src_y(src_y),
  .src_rgb(src_rgb),
  .dst_valid(dst_valid),
  .dst_frame_start(dst_frame_start),
  .nearest(nearest),
  .dst_x(dst_x),
  .dst_y(dst_y),
  .corners_valid(corners_valid),
  .marker_reject(marker_reject),
  .marker_dropped(marker_dropped),
  .solver_reject(solver_reject),
  .x0(x0),
  .y0(y0),
  .x1(x1),
  .y1(y1),
  .x2(x2),
  .y2(y2),
  .x3(x3),
  .y3(y3),
  .geometry_valid(geometry_valid),
  .params_pending(params_pending),
  .stale_frames(stale_frames),
  .req_valid(req_valid),
  .req_inside(req_inside),
  .req_error(req_error),
  .req_tag(req_tag),
  .addr00(addr00),
  .addr10(addr10),
  .addr01(addr01),
  .addr11(addr11),
  .req_fx(req_fx),
  .req_fy(req_fy),
  .rsp_valid(rsp_valid),
  .rsp_inside(rsp_inside),
  .rsp_tag(rsp_tag),
  .p00(p00),
  .p10(p10),
  .p01(p01),
  .p11(p11),
  .rsp_fx(rsp_fx),
  .rsp_fy(rsp_fy),
  .out_valid(out_valid),
  .out_rgb(out_rgb),
  .out_tag(out_tag)
 );
endmodule
